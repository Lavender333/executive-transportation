const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
test('Database enforces staff-only access and validates assignments', async t => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; grant usage on schema auth, public to anon, authenticated, service_role;
    create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
  `);
  await db.exec(fs.readFileSync('database/schema.sql', 'utf8'));
  await db.exec(fs.readFileSync('database/tracking.sql', 'utf8'));
  await db.exec("insert into public.staff_access(email) values ('staff@example.test')");
  const ride = { id: 'f1db366b-20cd-42ca-b22c-ddf7c9fec55a', customer_name: 'Test Passenger', email: 'customer@example.test', phone: '+1 555 010 1234', service: 'Airport transfer', pickup_date: '2030-06-16', pickup_time: '14:30', pickup_timezone: 'America/New_York', passengers: 2, pickup: 'Test airport', destination: 'Test hotel' };
  const insert = `insert into public.ride_requests(${Object.keys(ride).join(',')}) values(${Object.keys(ride).map((_, i) => '$' + (i + 1)).join(',')})`;
  await db.exec('set role service_role'); await db.query(insert, Object.values(ride)); await db.exec('reset role');
  await db.exec('set role anon');
  await assert.rejects(db.query('select * from public.ride_requests'), /permission denied/);
  await assert.rejects(db.query(insert, Object.values(ride)), /permission denied/);
  await assert.rejects(db.query("select public.consume_request_limit('x')"), /permission denied/);
  await db.exec('reset role');
  await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify({ email: 'outsider@example.test', user_metadata: { role: 'admin', email: 'staff@example.test' } })]);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from public.ride_requests')).rows.length, 0);
  assert.equal((await db.query('select * from public.staff_access')).rows.length, 0);
  await assert.rejects(db.query("insert into public.staff_access(email) values('outsider@example.test')"), /permission denied/);
  await assert.rejects(db.query("insert into public.drivers(name,phone,vehicle) values('Intruder','5550101234','Car')"), /row-level security/);
  await db.exec('reset role');
  await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify({ email: 'staff@example.test', is_anonymous: true })]);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from public.ride_requests')).rows.length, 0);
  await db.exec('reset role');
  await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify({ email: 'staff@example.test', is_anonymous: false })]);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from public.ride_requests')).rows.length, 1);
  await assert.rejects(db.query("update public.ride_requests set customer_name='Changed'"), /permission denied/);
  await assert.rejects(db.query("update public.ride_requests set status='assigned'"), /check constraint/);
  const driver = (await db.query("insert into public.drivers(name,phone,vehicle) values('Test Driver','5550101234','Sedan / TEST') returning id")).rows[0];
  const before = (await db.query('select updated_at from public.ride_requests')).rows[0].updated_at;
  await db.query("update public.ride_requests set status='confirmed'");
  assert.equal((await db.query("update public.ride_requests set status='cancelled' where updated_at=$1 returning id", [before])).rows.length, 0, 'Stale updates do not overwrite a newer change');
  await db.query("update public.drivers set active=false where id=$1", [driver.id]);
  await assert.rejects(db.query("update public.ride_requests set status='assigned',driver_id=$1", [driver.id]), /active driver/);
  await db.query("update public.drivers set active=true where id=$1", [driver.id]);
  await db.query("update public.ride_requests set status='assigned',driver_id=$1", [driver.id]);
  assert.equal((await db.query('select status from public.ride_requests')).rows[0].status, 'assigned');
  await db.exec('reset role; set role service_role');
  const operationalTime = (await db.query('select updated_at from public.ride_requests')).rows[0].updated_at;
  await db.query("update public.ride_requests set driver_token_hash='test-hash',driver_lat=40.75,driver_lng=-73.98,driver_accuracy=10,location_updated_at=now()");
  assert.equal(+(await db.query('select updated_at from public.ride_requests')).rows[0].updated_at, +operationalTime, 'Location updates do not conflict with dispatcher edits');
  await db.query("update public.ride_requests set status='completed'");
  const finished=(await db.query('select driver_token_hash,driver_lat from public.ride_requests')).rows[0];
  assert.equal(finished.driver_token_hash,null);assert.equal(finished.driver_lat,null);
  await db.exec('reset role');
  await db.exec("delete from public.staff_access where email='staff@example.test'");
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from public.ride_requests')).rows.length, 0, 'Removing membership immediately revokes access');
  await db.exec('reset role; set role service_role');
  for (let i = 0; i < 10; i++) assert.equal((await db.query("select public.consume_request_limit('test-key') as allowed")).rows[0].allowed, true);
  assert.equal((await db.query("select public.consume_request_limit('test-key') as allowed")).rows[0].allowed, false);
});
